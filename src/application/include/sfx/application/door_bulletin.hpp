#pragma once
#include "sfx/application/door.hpp"
#include "sfx/application/account_storage.hpp"
#include "sfx/application/presentation.hpp"
#include <functional>

namespace sfx::application {
// Door Bulletins have their own permanent identity; ordinary BBS bulletins
// retain their separate 1..99 range.
struct DoorBulletinId {std::uint16_t value{};bool operator==(const DoorBulletinId& other)const noexcept{return value==other.value;}};
enum class DoorBulletinSourceKind : std::uint8_t { display, door_file };
enum class DoorBulletinHealth : std::uint8_t { unchecked, available, unavailable };
struct DoorBulletinDefinition {
    DoorBulletinId id;
    std::string title;
    bool enabled{true};
    DoorBulletinSourceKind source{DoorBulletinSourceKind::display};
    DoorId door{};
    std::string relative_path;
    GraphicsMode format{GraphicsMode::ascii};
    std::int64_t revision{};
};
struct DoorBulletinEntry {
    DoorBulletinDefinition definition;
    DoorBulletinHealth health{DoorBulletinHealth::unchecked};
    std::optional<std::int64_t> published_utc;
};
struct DoorBulletinCatalog {std::int64_t revision{1};std::vector<DoorBulletinEntry> entries;};
struct DoorBulletinNotice {DoorBulletinId id;std::string title;};
struct DoorBulletinItem {DoorBulletinId id;std::string title;std::int64_t revision{};DoorBulletinHealth health{};};
struct DoorBulletinListing {std::int64_t revision{};std::vector<DoorBulletinItem> entries;};
struct DoorBulletinChange {
    Identifier128 operation;
    std::int64_t expected_revision{};
    DoorBulletinDefinition definition;
    bool remove{},create_only{};
};
// Host-only source description. Never include paths in caller menu/diagnostics.
struct DoorBulletinSource {
    DoorBulletinDefinition definition;
    std::int64_t door_revision{};
    std::string work_directory;
    bool door_available{}; // Empty approved directory means the installation root.
};
struct DoorBulletinPublication {
    DoorBulletinId id;
    std::int64_t definition_revision{},door_revision{};
    std::string variant; // Resolved static basename/format/security or generated format.
    bool available{};
    std::vector<std::uint8_t> captured_content; // Raw generated bytes only; no expanded caller data.
    std::string fingerprint_input; // Bounded captured raw assets, includes names and bytes.
};
struct DoorBulletinPublicationResult {DoorBulletinHealth health{};std::optional<std::int64_t> published_utc;bool changed{};};
bool valid_door_bulletin_id(DoorBulletinId) noexcept;
bool valid_door_bulletin_relative_path(std::string_view) noexcept;
bool valid_door_bulletin_definition(const DoorBulletinDefinition&) noexcept;
bool valid_door_bulletin_change(const DoorBulletinChange&) noexcept;
bool valid_door_bulletin_publication(const DoorBulletinPublication&) noexcept;
std::vector<std::uint8_t> encode_door_bulletin_catalog(const DoorBulletinCatalog&);
std::optional<DoorBulletinCatalog> decode_door_bulletin_catalog(const std::vector<std::uint8_t>&);
std::vector<std::uint8_t> encode_door_bulletin_change(const DoorBulletinChange&);
std::optional<DoorBulletinChange> decode_door_bulletin_change(const std::vector<std::uint8_t>&);
inline constexpr std::string_view kDoorBulletinUnavailable="This Door Bulletin is currently unavailable.";
} // namespace sfx::application
